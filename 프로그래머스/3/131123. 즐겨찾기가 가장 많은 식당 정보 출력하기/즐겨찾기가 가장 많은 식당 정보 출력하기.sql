select REST_INFO.FOOD_TYPE, REST_ID, REST_NAME, REST_INFO.FAVORITES
from REST_INFO
inner join (
    select FOOD_TYPE, max(FAVORITES) as MAX_FAVORITES
    from REST_INFO
    group by FOOD_TYPE
) as FOOD_MAX_FAVORITES on REST_INFO.FOOD_TYPE = FOOD_MAX_FAVORITES.FOOD_TYPE and REST_INFO.FAVORITES = FOOD_MAX_FAVORITES.MAX_FAVORITES
order by REST_INFO.FOOD_TYPE desc